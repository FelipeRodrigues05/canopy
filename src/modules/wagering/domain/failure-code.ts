/**
 * Stable machine-readable reasons. Part of the public contract: providers
 * branch on them, so values are never renamed.
 */
export const FailureCode = {
  INVALID_PAYLOAD: 'INVALID_PAYLOAD',
  IDEMPOTENCY_CONFLICT: 'IDEMPOTENCY_CONFLICT',
  WALLET_NOT_FOUND: 'WALLET_NOT_FOUND',
  WALLET_PLAYER_MISMATCH: 'WALLET_PLAYER_MISMATCH',
  CURRENCY_MISMATCH: 'CURRENCY_MISMATCH',
  INSUFFICIENT_FUNDS: 'INSUFFICIENT_FUNDS',
  REVERSAL_WOULD_OVERDRAW: 'REVERSAL_WOULD_OVERDRAW',
  REFERENCE_NOT_FOUND: 'REFERENCE_NOT_FOUND',
  REFERENCE_MISMATCH: 'REFERENCE_MISMATCH',
  INVALID_REFERENCE_KIND: 'INVALID_REFERENCE_KIND',
  REFERENCE_NOT_PROCESSED: 'REFERENCE_NOT_PROCESSED',
  AMOUNT_MISMATCH: 'AMOUNT_MISMATCH',
  ALREADY_REVERSED: 'ALREADY_REVERSED',
  INFRA_PERMANENT_FAILURE: 'INFRA_PERMANENT_FAILURE',
} as const;

export type FailureCode = (typeof FailureCode)[keyof typeof FailureCode];

export type FailureCategory = 'VALIDATION' | 'CONFLICT' | 'BUSINESS' | 'INFRA';

export const FAILURE_CATEGORY: Record<FailureCode, FailureCategory> = {
  INVALID_PAYLOAD: 'VALIDATION',
  IDEMPOTENCY_CONFLICT: 'CONFLICT',
  WALLET_NOT_FOUND: 'BUSINESS',
  WALLET_PLAYER_MISMATCH: 'BUSINESS',
  CURRENCY_MISMATCH: 'BUSINESS',
  INSUFFICIENT_FUNDS: 'BUSINESS',
  REVERSAL_WOULD_OVERDRAW: 'BUSINESS',
  REFERENCE_NOT_FOUND: 'BUSINESS',
  REFERENCE_MISMATCH: 'BUSINESS',
  INVALID_REFERENCE_KIND: 'BUSINESS',
  REFERENCE_NOT_PROCESSED: 'BUSINESS',
  AMOUNT_MISMATCH: 'BUSINESS',
  ALREADY_REVERSED: 'BUSINESS',
  INFRA_PERMANENT_FAILURE: 'INFRA',
};

export function isFailureCode(value: unknown): value is FailureCode {
  return typeof value === 'string' && Object.hasOwn(FailureCode, value);
}
